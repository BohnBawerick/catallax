pub(super) fn pair() -> [Vec<Vec<[Q; 3]>>; 2] {
    HEIGHTS.map(|net| {
        net.iter()
            .enumerate()
            .map(|(i, row)| {
                row.iter()
                    .enumerate()
                    .map(|(j, bits)| {
                        [
                            q(i as i64),
                            q(j as i64),
                            Q::from_f64_exact(f64::from_bits(*bits)).unwrap(),
                        ]
                    })
                    .collect()
            })
            .collect()
    })
}
