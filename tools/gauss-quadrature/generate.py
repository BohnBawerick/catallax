#!/usr/bin/env python3
"""Generate exact sign-certified brackets for the positive Legendre P8 roots."""
import argparse
from fractions import Fraction
from pathlib import Path

COEFFICIENTS = (6435, 0, -12012, 0, 6930, 0, -1260, 0, 35)
BRACKETS = ((0, Fraction(1, 4)), (Fraction(1, 2), Fraction(3, 5)),
            (Fraction(3, 4), Fraction(4, 5)), (Fraction(19, 20), 1))

def polynomial(x):
    value = Fraction(0)
    for coefficient in COEFFICIENTS:
        value = value * x + coefficient
    return value

def render():
    lines = ['// Generated by tools/gauss-quadrature/generate.py. Do not edit.',
             'pub(super) const NODE_INTERVALS: [(&str, &str); 4] = [']
    for low, high in BRACKETS:
        low, high = Fraction(low), Fraction(high)
        assert polynomial(low) * polynomial(high) < 0
        sign = polynomial(low) > 0
        while high - low > Fraction(1, 2**160):
            middle = (low + high) / 2
            assert polynomial(middle) != 0
            if (polynomial(middle) > 0) == sign:
                low = middle
            else:
                high = middle
        assert polynomial(low) * polynomial(high) < 0
        lines.extend(['    (', f'        "{low}",', f'        "{high}",', '    ),'])
    return '\n'.join([*lines, '];', ''])

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--out', type=Path)
    args = parser.parse_args()
    target = args.out or Path(__file__).resolve().parents[2] / 'crates/catallax-measure/src/integrate/gauss_nodes.rs'
    content = render()
    if args.check:
        if target.read_text() != content:
            raise SystemExit('Gauss root intervals need regeneration')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)

if __name__ == '__main__':
    main()
